// Embed the static page (web/index.html, web/app.js) into a TypeScript module the Lambda bundle
// carries, so the same origin that serves the API also serves the page (DESIGN §3.6, FINDINGS
// 2026-09-22 "$default stage serves the page same-origin"). The SAM build bundles only
// src/handler.ts with esbuild (README, template.yaml), which copies no loose files — so the page
// has to arrive as code. This script is the one place that turns the files into that code.
//
// web/ is the source of truth: edit the page there, then `npm run build:web` to regenerate
// src/webAssets.ts. test/web.test.ts fails if the two ever drift, so a forgotten regenerate is
// caught by `make server-test`, not discovered at deploy.
//
// Run: node scripts/gen-web-assets.mjs  (from server/)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL(".", import.meta.url));
const web = fileURLToPath(new URL("../web/", import.meta.url));
const out = fileURLToPath(new URL("../src/webAssets.ts", import.meta.url));

// path served → { source file, content type }. Keep in step with static.ts and index.html's
// <script src="/app.js">.
const ASSETS = [
  { path: "/", file: "index.html", contentType: "text/html; charset=utf-8" },
  { path: "/app.js", file: "app.js", contentType: "text/javascript; charset=utf-8" },
];

const entries = ASSETS.map(({ path, file, contentType }) => {
  const body = readFileSync(web + file, "utf8");
  // JSON.stringify yields a valid, fully escaped TS double-quoted string literal.
  return `  ${JSON.stringify(path)}: { contentType: ${JSON.stringify(contentType)}, body: ${JSON.stringify(body)} },`;
});

const module = `// GENERATED by scripts/gen-web-assets.mjs from web/. Do not edit by hand — edit web/index.html
// or web/app.js and run \`npm run build:web\`. test/web.test.ts asserts this file matches web/.
//
// The static page, embedded so the Lambda bundle can serve it same-origin (DESIGN §3.6). "/" is
// index.html and carries the \`__GOOGLE_CLIENT_ID__\` placeholder that static.ts fills at serve time.

export interface WebAsset {
  contentType: string;
  body: string;
}

export const webAssets: Record<string, WebAsset> = {
${entries.join("\n")}
};
`;

writeFileSync(out, module);
console.log(`wrote ${out.slice(dir.length - "scripts/".length)} from ${ASSETS.length} files`);
